"""Write docs/TRANSLATION_REVIEW.md: the checklist a fluent Tamil or Hindi speaker uses to review the draft text.

Usage: python scripts/make_translation_review.py
The file is generated from i18n/*.json, so it never drifts from the interface. Critical strings (those
that carry a claim, a limit or a warning) come first; every other string follows. Re-run after changing
any dictionary. Nothing here marks a translation as reviewed: that is done by a person (see the end).
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from src import i18n  # noqa: E402

OUT = ROOT / "docs" / "TRANSLATION_REVIEW.md"
# English phrases whose meaning must survive translation, and what to tell the reviewer
MUST_KEEP = [
    (r"simulat", "says the data or result is **simulated**"),
    (r"indicative", "says it is **indicative**"),
    (r"not (a )?(prediction|forecast)|not predictions", "says it is **not a prediction**"),
    (r"placeholder", "says the weights are **placeholders**"),
    (r"not (of )?people|not people", "says it is **not people**"),
    (r"unverified|not phone-verified", "says the facility is **unverified**"),
    (r"proxy", "says the facility list is a **proxy**"),
    (r"not for live dispatch", "says **not for live dispatch**"),
    (r"today's roads|not 2015", "says these are **today's roads, not 2015 roads**"),
    (r"composite", "says the layer is a **composite**"),
]
PLACEHOLDER = re.compile(r"\{(\w+)\}")


def must_keep(english: str) -> str:
    notes = [msg for pat, msg in MUST_KEEP if re.search(pat, english, re.I)]
    holders = sorted(set(PLACEHOLDER.findall(english)))
    if holders:
        notes.append("keeps " + ", ".join("`{" + h + "}`" for h in holders) + " exactly as written")
    return "; ".join(notes) or "meaning matches the English"


def cell(text: str) -> str:
    return text.replace("|", "/").replace("\n", " ")


def is_critical(key: str) -> bool:
    return key in i18n.CRITICAL_KEYS or key.startswith(i18n.CRITICAL_PREFIXES)


def table(keys, en, ta, hi) -> list:
    lines = ["| # | Key | English (reference) | Tamil (draft) | Hindi (draft) | What to check | ta OK | hi OK | Corrections |",
             "|---|---|---|---|---|---|---|---|---|"]
    for n, k in enumerate(keys, 1):
        lines.append(f"| {n} | `{k}` | {cell(en[k])} | {cell(ta[k])} | {cell(hi[k])} | {cell(must_keep(en[k]))} | [ ] | [ ] | |")
    return lines


def main() -> None:
    en, ta, hi = (i18n.load_dictionary(l) for l in ("en", "ta", "hi"))
    keys = [k for k in en if k != "_meta"]
    critical = [k for k in keys if is_critical(k)]
    other = [k for k in keys if not is_critical(k)]
    md = [
        "# Tamil and Hindi translation review",
        "",
        "Generated by `scripts/make_translation_review.py` from `i18n/*.json`. **All Tamil and Hindi text was written by an AI assistant and is a draft.** "
        "The interface says so on the Data and limits page until a fluent speaker signs off below (blueprint I18N-13).",
        "",
        f"- Strings in the interface: **{len(keys)}** per language.",
        f"- Critical strings (claims, limits, warnings): **{len(critical)}**. Review these first and before any demo recording.",
        f"- Other interface strings: **{len(other)}**.",
        "",
        "## How to review",
        "1. Read the English (reference) and the draft in your language side by side. Tick the box when the meaning matches and the wording is natural; write a better version in the *Corrections* column otherwise.",
        "2. **A critical string must never weaken a claim.** If the English says *simulated*, *indicative*, *not a prediction*, *placeholder*, *unverified* or *proxy*, the translation must say the same. The *What to check* column names what each string must keep.",
        "3. Do not translate or change `{placeholders}` (for example `{facility}`, `{time}`): the program fills them in. Word order around them may change.",
        "4. Facility names (for example *GCC emergency obstetric unit, Saidapet*) are intentionally not translated. Numbers use Western digits with Indian grouping (12,34,567).",
        "5. Check the text on screen too: open the app with `?lang=ta` or `?lang=hi` and look for cut-off words, missing glyph boxes, or text that overflows a button.",
        "6. Medical and flood terms: prefer the term a Chennai resident would use in speech over a literal dictionary word.",
        "",
        "## Sign-off",
        "| Language | Reviewer name | Role or qualification | Date | Critical strings checked | All strings checked | Verdict (approve / approve with corrections / reject) |",
        "|---|---|---|---|---|---|---|",
        f"| Tamil | | | | 0 of {len(critical)} | 0 of {len(keys)} | |",
        f"| Hindi | | | | 0 of {len(critical)} | 0 of {len(keys)} | |",
        "",
        f"## A. Critical strings ({len(critical)})",
        "",
        *table(critical, en, ta, hi),
        "",
        f"## B. Other interface strings ({len(other)})",
        "",
        *table(other, en, ta, hi),
        "",
        "## After the review",
        "1. Apply the corrections to `i18n/ta.json` and `i18n/hi.json` (keep every key and every `{placeholder}`).",
        "2. In the same file set `_meta.status` to `\"reviewed\"`, and fill `reviewed_by` and `reviewed_on` (YYYY-MM-DD) with the reviewer's name and the date.",
        "3. Run `python scripts/export_web_i18n.py` and `python -m pytest`. The tests check that all three languages have the same keys and placeholders.",
        "4. Re-run `python scripts/make_translation_review.py` and `python scripts/build_routes.py` (explanation sentences are stored in `routes.json` in all three languages).",
        "5. Record the reviewer in this file's sign-off table and in `docs/PREVIEW_LOG.md`.",
        "",
        "Until step 2 is done for a language, the interface keeps showing that language as *Draft (not yet reviewed)*.",
        "",
    ]
    OUT.write_text("\n".join(md), encoding="utf-8")
    print(f"wrote {OUT} ({len(critical)} critical, {len(other)} other)")


if __name__ == "__main__":
    main()
